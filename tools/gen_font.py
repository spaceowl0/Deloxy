#!/usr/bin/env python3
"""Generate src/gfx/font.rs: 8x16 bitmap glyphs for ASCII 32..126 rasterised from DejaVu Sans Mono
(Bitstream Vera licence - see NOTICE). Needs Pillow + fonts-dejavu-core. Output is committed, so this
only needs re-running to change the font."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(FONT, 13)
asc, desc = font.getmetrics()
glyphs = []
for code in range(32, 127):
    img = Image.new("1", (8, 16), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((0, 0 + (13 - asc) // 2), chr(code), font=font, fill=1, anchor="la")
    rows = []
    for y in range(16):
        v = 0
        for x in range(8):
            if img.getpixel((x, y)):
                v |= 0x80 >> x
        rows.append(v)
    glyphs.append(rows)

out = ["//! 8x16 bitmap font, ASCII 32..=126. Generated by tools/gen_font.py from DejaVu Sans Mono",
       "//! (Bitstream Vera licence). Bit 7 of each byte is the leftmost pixel.", "",
       "pub const GLYPH_W: usize = 8;", "pub const GLYPH_H: usize = 16;", "",
       "pub static FONT8X16: [[u8; 16]; 95] = ["]
for code, rows in zip(range(32, 127), glyphs):
    out.append("    [" + ", ".join("0x%02X" % r for r in rows) + "], // %r" % chr(code))
out.append("];")
open(sys.argv[1] if len(sys.argv) > 1 else "src/gfx/font.rs", "w").write("\n".join(out) + "\n")
if "--preview" in sys.argv:
    for ch in "Aa&g@":
        for r in glyphs[ord(ch) - 32]:
            print("".join("#" if r & (0x80 >> x) else "." for x in range(8)))
        print()
