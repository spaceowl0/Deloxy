#!/usr/bin/env python3
"""Regenerate src/upd/testvec.rs: signed manifests produced by the Python reference signer, so the in-kernel
Ed25519/SHA-256 code is checked against an independent implementation without needing any network."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import importlib.util
spec = importlib.util.spec_from_file_location("srv", os.path.join(os.path.dirname(os.path.abspath(__file__)), "mock-update-server.py"))
srv = importlib.util.module_from_spec(spec); spec.loader.exec_module(srv)
r = srv.build()

def lit(name, data):
    return "pub static %s: &[u8] = &[%s];\n" % (name, ", ".join(str(b) for b in data))

out = "//! GENERATED by tools/gen-upd-testvec.py - do not edit. Self-test vectors for deloxy-upd.\n"
out += lit("MANIFEST_OK", r["/ok/manifest.json"]) + lit("SIG_OK", r["/ok/manifest.sig"])
out += lit("MANIFEST_TAMPERED", r["/tampered/manifest.json"])
out += lit("SIG_WRONGKEY", r["/wrongkey/manifest.sig"]) + lit("SIG_FORGED", r["/forged/manifest.sig"])
out += lit("MANIFEST_MALFORMED", r["/malformed/manifest.json"]) + lit("SIG_MALFORMED", r["/malformed/manifest.sig"])
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "upd", "testvec.rs"), "w").write(out)
print("wrote src/upd/testvec.rs")
